文字 = "茅台 五粮液 茅台 宁德 茅台 五粮液"

# 1. 用 split() 把文字按空格拆成单词列表
#    "茅台 五粮液".split() → ["茅台", "五粮液"]
词列表 = 文字.split()

# 2. 建一个空字典来计数
统计 = {}

# 3. for 循环遍历每个词
for 词 in 词列表:
    if 词 in 统计:                    # 这个词已经出现过？
        统计[词] = 统计[词] + 1       # 是 → 计数+1
    else:                             # 没出现过？
        统计[词] = 1                  # 否 → 创建，计数=1

# 4. 打印结果
for 词 in 统计:
    print(f"{词}: {统计[词]} 次")